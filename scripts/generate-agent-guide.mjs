import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = new URL('../', import.meta.url);
export async function renderAgentGuide() {
  const skill = (await readFile(new URL('skills/mail-mcp/SKILL.md', root), 'utf8')).replace(/\r\n/g, '\n');
  const directory = new URL('skills/mail-mcp/references/', root);
  const names = (await readdir(directory)).filter(name => name.endsWith('.md')).sort();
  // Each portable file has its own runtime resource; links never imply loading all topics.
  const runtimeText = text => text.trim().replace(
    /\[([^\]]+)\]\((?:references\/)?([a-z-]+)\.md(#[^)]+)?\)/g,
    (_, label, topic) => `[${label}](mail://reference/${topic})`,
  ) + '\n';
  const text = runtimeText(skill.replace(/^---\n[\s\S]*?\n---\n/, ''));
  const references = [];
  for (const name of names) {
    const content = (await readFile(new URL(name, directory), 'utf8')).replace(/\r\n/g, '\n');
    const title = content.match(/^# (.+)$/m)?.[1];
    if (!title) throw new Error(`Reference ${name} needs a title.`);
    references.push({ topic: name.slice(0, -3), title, text: runtimeText(content) });
  }
  return '// Generated by scripts/generate-agent-guide.mjs. Edit skills/mail-mcp instead.\n'
    + `export const MAIL_AGENT_GUIDE = ${JSON.stringify(text)};\n`
    + `export const MAIL_REFERENCE_DOCUMENTS = ${JSON.stringify(references, null, 2)} as const;\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = new URL('src/mcp/agent-guide-content.ts', root);
  const rendered = await renderAgentGuide();
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current.replace(/\r\n/g, '\n') !== rendered) throw new Error('Agent guide is stale. Run npm run docs:generate.');
    console.log('Runtime core guide and topic resources match the portable skill.');
  } else {
    await writeFile(target, rendered, 'utf8');
    console.log('Generated the core guide and on-demand topic resources.');
  }
}
