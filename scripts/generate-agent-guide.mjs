import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = new URL('../', import.meta.url);
export async function renderAgentGuide() {
  const skill = (await readFile(new URL('skills/mail-mcp/SKILL.md', root), 'utf8')).replace(/\r\n/g, '\n');
  const directory = new URL('skills/mail-mcp/references/', root);
  const names = (await readdir(directory)).filter(name => name.endsWith('.md')).sort();
  const parts = [skill.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').trim()];
  for (const name of names) parts.push((await readFile(new URL(name, directory), 'utf8')).replace(/\r\n/g, '\n').trim());
  // Runtime resource is self-contained: filesystem links become section labels.
  const text = parts.join('\n\n---\n\n').replace(/\[([^\]]+)\]\((?:references\/)?[a-z-]+\.md\)/g, '$1 (section below)');
  return '// Generated by scripts/generate-agent-guide.mjs. Edit skills/mail-mcp instead.\n'
    + `export const MAIL_AGENT_GUIDE = ${JSON.stringify(text + '\n')};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = new URL('src/mcp/agent-guide-content.ts', root);
  const rendered = await renderAgentGuide();
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current.replace(/\r\n/g, '\n') !== rendered) throw new Error('Agent guide is stale. Run npm run docs:generate.');
    console.log('Runtime guide matches the portable skill and all references.');
  } else {
    await writeFile(target, rendered, 'utf8');
    console.log('Generated the self-contained runtime guide.');
  }
}
